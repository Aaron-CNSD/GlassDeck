import AppKit

/// One captured clipboard item.
///
/// Text only: images would balloon the on-disk history and the deck has no
/// thumbnail surface to show them anyway. `pinned` items survive trimming.
struct ClipboardEntry: Codable, Equatable {
    let id: UUID
    let text: String
    let capturedAt: Date
    var pinned: Bool

    init(id: UUID = UUID(), text: String, capturedAt: Date = Date(), pinned: Bool = false) {
        self.id = id
        self.text = text
        self.capturedAt = capturedAt
        self.pinned = pinned
    }

    /// A single-line preview: newlines and runs of spaces collapsed, capped so
    /// a 20 KB log paste does not turn one row into a wall of text.
    var preview: String {
        let flattened = text
            .replacingOccurrences(of: "\r\n", with: "\n")
            .split(whereSeparator: { $0 == "\n" || $0 == "\t" })
            .map { $0.trimmingCharacters(in: .whitespaces) }
            .filter { !$0.isEmpty }
            .joined(separator: " ")
        if flattened.isEmpty { return text.trimmingCharacters(in: .whitespacesAndNewlines) }
        return flattened.count > 120 ? String(flattened.prefix(120)) + "…" : flattened
    }

    /// "2 min ago" style stamp, localized by the system formatter.
    var relativeTime: String {
        let formatter = RelativeDateTimeFormatter()
        formatter.unitsStyle = .short
        return formatter.localizedString(for: capturedAt, relativeTo: Date())
    }
}

/// Local clipboard history.
///
/// The store polls `NSPasteboard.changeCount` instead of installing an event
/// tap: polling needs no Accessibility permission, costs one integer read per
/// tick, and cannot see keystrokes. Items marked concealed or transient by the
/// source app (password managers do this) are never recorded. History lives on
/// this Mac only — `~/Library/Application Support/GlassDeck/clipboard.json`.
final class ClipboardStore {

    static let shared = ClipboardStore()

    /// Posted on the main thread whenever the history changes.
    static let changed = Notification.Name("GlassDeckClipboardChanged")

    /// UserDefaults key for the record/stop switch.
    static let enabledKey = "GlassDeck.clipboardCapture"

    /// Unpinned items kept on disk. Pinned items are kept on top of this.
    static let historyLimit = 60

    /// Longer paste is almost always a file dump, not something worth keeping.
    static let maxCharacters = 100_000

    private(set) var entries: [ClipboardEntry] = []

    private var timer: Timer?
    private var lastChangeCount: Int

    private init() {
        lastChangeCount = NSPasteboard.general.changeCount
        load()
    }

    // MARK: - Switch

    /// Recording defaults to on: a clipboard shelf nobody notices is a shelf
    /// nobody uses. The switch in the Clipboard tab turns it off for good.
    var isEnabled: Bool {
        get {
            let defaults = UserDefaults.standard
            if defaults.object(forKey: Self.enabledKey) == nil { return true }
            return defaults.bool(forKey: Self.enabledKey)
        }
        set {
            UserDefaults.standard.set(newValue, forKey: Self.enabledKey)
            newValue ? start() : stop()
        }
    }

    // MARK: - Monitoring

    /// Begins polling when recording is enabled. Safe to call repeatedly.
    func start() {
        guard isEnabled, timer == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.8, repeats: true) { [weak self] _ in
            self?.poll()
        }
        // .common keeps the timer alive while a menu or the popover is tracking.
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard !Self.isConcealed(pasteboard) else { return }
        guard let text = pasteboard.string(forType: .string) else { return }
        capture(text)
    }

    /// Password managers and other privacy-conscious apps flag their paste so
    /// clipboard managers skip it. Respect that.
    private static func isConcealed(_ pasteboard: NSPasteboard) -> Bool {
        let skipped = [
            NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
            NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
            NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        ]
        let types = pasteboard.types ?? []
        return skipped.contains { types.contains($0) }
    }

    // MARK: - Mutation

    /// Records `text` unless it is empty, oversized, or already the newest item.
    func capture(_ text: String) {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty, trimmed.count <= Self.maxCharacters else { return }
        guard entries.first?.text != text else { return }

        entries.insert(ClipboardEntry(text: text), at: 0)
        trim()
        persist()
        notify()
    }

    func togglePin(_ id: UUID) {
        guard let index = entries.firstIndex(where: { $0.id == id }) else { return }
        entries[index].pinned.toggle()
        trim()
        persist()
        notify()
    }

    func remove(_ id: UUID) {
        entries.removeAll { $0.id == id }
        persist()
        notify()
    }

    /// Wipes everything, including pinned items.
    func clear() {
        entries.removeAll()
        persist()
        notify()
    }

    /// Puts an entry back on the system pasteboard. Marks it as the newest item
    /// so re-copying does not create a duplicate.
    func copyToPasteboard(_ id: UUID) {
        guard let entry = entries.first(where: { $0.id == id }) else { return }
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(entry.text, forType: .string)
        lastChangeCount = pasteboard.changeCount
    }

    /// Pinned items first (newest first), then the rest in capture order, and
    /// never more than `historyLimit` unpinned items.
    private func trim() {
        entries.sort { lhs, rhs in
            if lhs.pinned != rhs.pinned { return lhs.pinned }
            return lhs.capturedAt > rhs.capturedAt
        }
        var unpinned = 0
        entries = entries.filter { entry in
            guard !entry.pinned else { return true }
            unpinned += 1
            return unpinned <= Self.historyLimit
        }
    }

    // MARK: - Persistence

    private static var storageURL: URL? {
        guard let support = FileManager.default.urls(for: .applicationSupportDirectory,
                                                    in: .userDomainMask).first else { return nil }
        let folder = support.appendingPathComponent("GlassDeck", isDirectory: true)
        try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        return folder.appendingPathComponent("clipboard.json")
    }

    private func load() {
        guard let url = Self.storageURL,
              let data = try? Data(contentsOf: url),
              let decoded = try? JSONDecoder().decode([ClipboardEntry].self, from: data) else { return }
        entries = decoded
        trim()
    }

    private func persist() {
        guard let url = Self.storageURL,
              let data = try? JSONEncoder().encode(entries) else { return }
        try? data.write(to: url, options: .atomic)
    }

    private func notify() {
        if Thread.isMainThread {
            NotificationCenter.default.post(name: Self.changed, object: nil)
        } else {
            DispatchQueue.main.async { NotificationCenter.default.post(name: Self.changed, object: nil) }
        }
    }
}
